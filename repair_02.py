def process_file(filepath, corrections):
    """Read JSON, apply corrections, write back, return count of changes."""
    full_path = os.path.join(WORD_DIR, filepath)
    with open(full_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    changes = 0
    for (di, ei), new_t in corrections.items():
        if di < len(data['defs']):
            d = data['defs'][di]
            if ei < len(d['ex']):
                old_t = d['ex'][ei].get('t', '')
                if old_t != new_t:
                    d['ex'][ei]['t'] = new_t
                    changes += 1

    # Write back
    with open(full_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'))

    return changes


def main():
    total_changes = 0
    for filepath in FILES:
        corrections = CORRECTIONS.get(filepath, {})
        changes = process_file(filepath, corrections)
        total_changes += changes
        print(f"{filepath}: {changes} corrections applied")

    print(f"\nTotal corrections: {total_changes}")
    print(f"Total files processed: {len(FILES)}")


if __name__ == '__main__':
    main()
